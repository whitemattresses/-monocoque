// Same shape as Dictionary, but every string leaf widened to `string`.
// Non-default locale dictionaries carry different copy than en.ts, so their
// leaves can't stay string literals — this keeps the nested object/array
// structure enforced while allowing arbitrary translated text.
type DeepWiden<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly DeepWiden<U>[]
    : T extends object
      ? { readonly [K in keyof T]: DeepWiden<T[K]> }
      : T;

export type LocalizedDictionary = DeepWiden<Dictionary>;
